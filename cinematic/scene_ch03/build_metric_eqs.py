"""Chapter 3's metric + loss definitions, LaTeX-compiled to SVG (the
director wanted the Chapter 3 deeper dive to define F1, accuracy,
precision and recall too — in fact every metric the model reports, and
the form of the loss function). The same renderer as Chapter 1's theory
equations (scene_ch01/build_theory_eqs.py: latex + dvisvgm, Computer
Modern).

Sources: ESSD manuscript v3 (cinematic/source_data/manuscript_essd/
revision_v3/main_blue_20260920.tex) — Sect. 3 (the inter-rater κ),
Appendix B "Class weighting" / "Optimization" / the F1 equation and Table
B1 ("Inverse-frequency weighted cross-entropy"); the weighted mean is
torch.nn.CrossEntropyLoss(weight=w)'s (lakevision_src_rev).

Outputs:
  cinematic/data/eq_ch03/<name>.svg       (upload to R2 ch03/eq/)
  website/src/config/ch3Eqs.ts            (sizes in bp, committed)
Run:
  cinematic/.venv/bin/python cinematic/scene_ch03/build_metric_eqs.py
Then:
  rclone copy cinematic/data/eq_ch03 r2:<bucket>/ch03/eq --header-upload 'Cache-Control: public, max-age=31536000, immutable'
  mkdir -p website/.r2-cache/ch03/eq && cp cinematic/data/eq_ch03/*.svg website/.r2-cache/ch03/eq/
"""
import sys
import tempfile
from pathlib import Path

ROOT = Path(__file__).resolve().parents[2]
sys.path.insert(0, str(ROOT / "cinematic" / "scene_ch01"))
import build_theory_eqs as T  # noqa: E402  (the renderer: compile_one, set_box, math)

OUT = ROOT / "cinematic" / "data" / "eq_ch03"
TS_OUT = ROOT / "website" / "src" / "config" / "ch3Eqs.ts"

# name: (tex, source)  — all display math, ink
EQS = {
    "cm": (r"N_{ij} = \#\{\text{lakes of true class } i \text{ predicted as } j\}, \qquad "
           r"\mathrm{TP}_c = N_{cc}, \quad \mathrm{FP}_c = \sum_{i \neq c} N_{ic}, \quad \mathrm{FN}_c = \sum_{j \neq c} N_{cj}",
           "the confusion matrix (Fig. B3) and its per-class counts"),
    "acc": (r"A = \frac{1}{N}\sum_{c=1}^{K} N_{cc}", "accuracy (Table B2, A)"),
    "prec": (r"P_c = \frac{\mathrm{TP}_c}{\mathrm{TP}_c + \mathrm{FP}_c}", "per-class precision"),
    "rec": (r"R_c = \frac{\mathrm{TP}_c}{\mathrm{TP}_c + \mathrm{FN}_c}", "per-class recall"),
    "f1c": (r"F_{1,c} = \frac{2\,P_c\,R_c}{P_c + R_c} = \frac{2\,\mathrm{TP}_c}{2\,\mathrm{TP}_c + \mathrm{FP}_c + \mathrm{FN}_c}",
            "Appendix B, the F1 equation"),
    "macro": (r"P = \frac{1}{K}\sum_{c=1}^{K} P_c, \qquad R = \frac{1}{K}\sum_{c=1}^{K} R_c, \qquad "
              r"F_1 = \frac{1}{K}\sum_{c=1}^{K} F_{1,c}",
              "macro-averaging (Appendix B; Table B2's P, R, F1)"),
    "floor": (r"F_1^{\,\mathrm{random}} = \frac{1}{K} \quad (0.20 \text{ five-class},\ 0.25 \text{ four-class})",
              "the random-guess floor on the training curves (Sect. 6; build_training_dynamics.py RUNS)"),
    "softmax": (r"p_c(\mathbf{x}) = \frac{\exp z_c(\mathbf{x})}{\sum_{k=1}^{K} \exp z_k(\mathbf{x})}",
                "class probabilities from the head's logits (Sect. 4.3)"),
    "wc": (r"w_c = \frac{N_{\mathrm{train}}}{K\,n_c}, \qquad N_{\mathrm{train}} = 600",
           "Appendix B, Class weighting"),
    "loss": (r"\mathcal{L} = -\,\frac{\displaystyle\sum_{i \in \text{batch}} w_{y_i}\,\log p_{y_i}(\mathbf{x}_i)}"
             r"{\displaystyle\sum_{i \in \text{batch}} w_{y_i}}",
             "inverse-frequency weighted cross-entropy (Table B1; torch CrossEntropyLoss(weight=w), mean reduction)"),
    "kappa": (r"\kappa = \frac{p_o - p_e}{1 - p_e}, \qquad p_o = \frac{1}{N}\sum_{c} N_{cc}, \quad "
              r"p_e = \sum_{c} \frac{N_{c\cdot}}{N}\,\frac{N_{\cdot c}}{N}",
              "Cohen's kappa between two labelers (Sect. 3.4; kappa_12 = 0.744)"),
}


def main() -> None:
    OUT.mkdir(parents=True, exist_ok=True)
    manifest = {}
    with tempfile.TemporaryDirectory() as td:
        wd = Path(td)
        for name, (tex, src) in EQS.items():
            svg, dims = T.compile_one(T.math(tex, True), None, "ink", wd, name)
            svg, W, H, base = T.set_box(svg, dims["w"], dims["h"], dims["d"])
            (OUT / f"{name}.svg").write_text(svg)
            manifest[name] = dict(w=W, h=H, base=base, src=src)
            print(f"  {name:8s} {W:7.2f} x {H:6.2f} bp   [{src}]")
    lines = [
        "// GENERATED by cinematic/scene_ch03/build_metric_eqs.py — do not edit.",
        "// LaTeX-compiled (Computer Modern) Chapter 3 metric + loss definitions,",
        "// served from R2 ch03/eq/<name>.svg. Sizes in bp (1/72 in): w × h is the",
        "// whole image (TeX box + pad), base = image top → baseline.",
        "export interface EqBox { w: number; h: number; base: number }",
        "export const CH3_EQ = {",
    ]
    for name, e in manifest.items():
        lines.append(f"  {name}: {{ w: {e['w']:.3f}, h: {e['h']:.3f}, base: {e['base']:.3f} }}, // {e['src']}")
    lines.append("} as const satisfies Record<string, EqBox>")
    lines.append("export type Ch3EqName = keyof typeof CH3_EQ")
    TS_OUT.write_text("\n".join(lines) + "\n")
    print(f"wrote {len(manifest)} entries -> {TS_OUT.relative_to(ROOT)}")


if __name__ == "__main__":
    main()
