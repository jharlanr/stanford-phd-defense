"""Bake Chapter 3's IMPLICATIONS figure: RATE -> MECHANISM.

The director's note: Chapter 3 needed a real implications page, and the
implication is that lakes can be classified by mechanism and not just by
rate — and that this is what the field should strive for.

The figure is the SAME 1000 CW2019 lakes classified two ways, an alluvial
from the rate-based classes of Dunmire et al. (2025) on the left to the
five drainage-mechanism classes of the ESSD dataset on the right. A rate
class splitting across several mechanisms is the point: rate alone cannot
tell the mechanisms apart.

Inputs (repo copies — read only, never modified):
  source_data/essd/labels/labels_CW_2019.csv
      lake_id, label in {ND, HF, MD, LD, CD}  (the ESSD hand labels)
  source_data/essd/dunmire/labels_2019_volumes.geojson
      new_id (= the same CW2019_#### ids), final_label in {0,1,2,3}

Dunmire's codes (Dunmire et al. 2025, Earth and Space Science,
doi:10.1029/2024EA003793, Fig. 1 caption and Sect. 3.2.1): "refreeze
(class 0), rapidly drains (class 1), slowly drains (class 2), and becomes
buried (class 3)"; rapid = p_water falls to 20 % of its maximum in < 6
days (after Morriss et al. 2013). Checks against that paper: 1096 lakes
GrIS-wide carry code 0 in 2019 ("1096 lakes (18 % of all 2019 lakes)
refreeze"), and only code 1 carries a drain_date.

Join rule: ESSD lake_id == Dunmire new_id, exact string match (the ESSD
lakes ARE Dunmire's CW lakes, same ids — ESSD paper Sect. 2.1).

Output (generated, committed):
  website/src/config/ch3Implications.gen.ts

Run:  python3 cinematic/scene_ch03/build_implications.py
"""

from __future__ import annotations

import csv
import json
from collections import Counter
from pathlib import Path

ROOT = Path(__file__).resolve().parents[2]
SRC = ROOT / 'cinematic' / 'source_data' / 'essd'
LABELS = SRC / 'labels' / 'labels_CW_2019.csv'
DUNMIRE = SRC / 'dunmire' / 'labels_2019_volumes.geojson'
OUT = ROOT / 'website' / 'src' / 'config' / 'ch3Implications.gen.ts'

# Dunmire et al. 2025's class codes, in their own words (Fig. 1).
RATE = [
    (1, 'rapid', 'Rapidly drains'),
    (2, 'slow', 'Slowly drains'),
    (0, 'refreeze', 'Refreezes'),
    (3, 'buried', 'Becomes buried'),
]
# The mechanism side, top to bottom: the fast-draining mechanisms first,
# no drainage last — the order that crosses the fewest ribbons.
MECH = ['HF', 'MD', 'CD', 'LD', 'ND']


def main() -> None:
    labels = list(csv.DictReader(LABELS.open()))
    feats = json.loads(DUNMIRE.read_text())['features']
    dun = {f['properties']['new_id']: f['properties'] for f in feats}

    matched = [r for r in labels if r['lake_id'] in dun]
    missing = sorted(r['lake_id'] for r in labels if r['lake_id'] not in dun)
    codes = {c for c, _, _ in RATE}
    odd = sorted(r['lake_id'] for r in matched if dun[r['lake_id']]['final_label'] not in codes)
    if odd:
        raise SystemExit(f'unknown Dunmire codes on {odd[:5]}…')

    ct = Counter((dun[r['lake_id']]['final_label'], r['label']) for r in matched)
    matrix = [[ct[(c, m)] for m in MECH] for c, _, _ in RATE]

    # print the crosstab
    w = 16
    print(f"{'':{w}}" + ''.join(f'{m:>6}' for m in MECH) + f"{'total':>7}")
    for (c, _, name), row in zip(RATE, matrix):
        print(f'{name:{w}}' + ''.join(f'{v:>6}' for v in row) + f'{sum(row):>7}')
    col = [sum(matrix[i][j] for i in range(len(RATE))) for j in range(len(MECH))]
    print(f"{'total':{w}}" + ''.join(f'{v:>6}' for v in col) + f'{sum(col):>7}')
    print(f'matched {len(matched)} / {len(labels)}; missing {len(missing)}')

    rate_ts = ',\n'.join(
        f"  {{ code: {c}, id: '{i}', name: '{n}' }}" for c, i, n in RATE
    )
    rows_ts = '\n'.join(
        f"  [{', '.join(str(v) for v in row)}], // {n}" for (_, _, n), row in zip(RATE, matrix)
    )
    OUT.write_text(
        f"""// GENERATED by cinematic/scene_ch03/build_implications.py — do not edit by hand.
//
// Chapter 3's implications figure: the 2019 central-west lakes classified
// by RATE (Dunmire et al. 2025's four classes, final_label in
// source_data/essd/dunmire/labels_2019_volumes.geojson) and by MECHANISM
// (the ESSD hand labels, source_data/essd/labels/labels_CW_2019.csv).
// Join: ESSD lake_id == Dunmire new_id, exact match.
// Matched {len(matched)} of {len(labels)} labeled lakes; missing: {json.dumps(missing)}.

/** Dunmire et al. 2025's rate classes, top to bottom; `code` = final_label. */
export const CH3_IMPL_RATE = [
{rate_ts},
] as const

/** The mechanism classes, top to bottom. */
export const CH3_IMPL_MECH = {json.dumps(MECH).replace('"', "'")} as const

/** Lake counts: COUNTS[rate row][mechanism column]. */
export const CH3_IMPL_COUNTS: number[][] = [
{rows_ts}
]

export const CH3_IMPL_MATCHED = {len(matched)}
export const CH3_IMPL_LABELED = {len(labels)}
export const CH3_IMPL_MISSING: string[] = {json.dumps(missing)}
"""
    )
    print(f'wrote {OUT.relative_to(ROOT)}')


if __name__ == '__main__':
    main()
