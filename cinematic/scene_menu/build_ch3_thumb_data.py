#!/usr/bin/env python3
"""Chapter 3 menu-card data: the director wanted the card to show more of
the architecture and less of an image hopping from one stage to the next.

The card draws the chapter's network road map (EssdNetworkDiagram) in
miniature, with a light walking the forward pass once per example lake.
The data glyphs it carries are the chapter's own, at the season's last day
(30 Sep 2019, the day the verdict is read):

  pw     the network's p_water input (min-max, 153 days)
  gap    the ConvLSTM state after global average pooling (32), divided by
         the season's largest |v| — the diagram's symmetric scale
  slstm  the scalar LSTM state (16), same scaling
  hidden the head's hidden layer (64, post-ReLU), same scaling
  probs  the softmax (ND HF MD LD CD)

Reads only the repo's R2 mirror of the chapter bake (website/.r2-cache/
ch03/network/<lake>/manifest.json, written by cinematic/scene_ch03/
build_network.py) and writes a small TypeScript module next to the thumb,
so the card fetches nothing but the five 18 kB lake thumbnails the chapter
already uses. Nothing is uploaded.

  python3 cinematic/scene_menu/build_ch3_thumb_data.py
"""
import json
from pathlib import Path

ROOT = Path(__file__).resolve().parents[2]
SRC = ROOT / 'website' / '.r2-cache' / 'ch03' / 'network'
OUT = ROOT / 'website' / 'src' / 'components' / 'menu_thumbs' / 'ch3ThumbData.ts'
# Pass order: the chapter's default lake first, then round the classes.
LAKES = ['CW2019_1848', 'CW2019_1907', 'CW2019_2330', 'CW2019_1597', 'CW2019_1889']


def sym_scale(rows):
    return max(abs(v) for r in rows for v in r) or 1.0


def r2(xs):
    return [round(float(x), 2) for x in xs]


def main() -> None:
    index = json.loads((SRC / 'index.json').read_text())
    out = []
    for lake in LAKES:
        m = json.loads((SRC / lake / 'manifest.json').read_text())
        v = m['vectors']
        last = m['days'] - 1
        s_gap, s_slstm, s_hidden = sym_scale(v['gap']), sym_scale(v['slstm']), sym_scale(v['hidden'])
        out.append({
            'lake': lake,
            'true': m['true'],
            'pred': m['prediction']['pred'],
            'pw': r2(m['p_water_input']),
            'gap': r2([max(-1.0, min(1.0, x / s_gap)) for x in v['gap'][last]]),
            'slstm': r2([max(-1.0, min(1.0, x / s_slstm)) for x in v['slstm'][last]]),
            'hidden': r2([max(0.0, min(1.0, x / s_hidden)) for x in v['hidden'][last]]),
            'probs': [round(float(p), 3) for p in v['probs'][last]],
        })
    body = ',\n'.join('  ' + json.dumps(o, separators=(',', ':')) for o in out)
    OUT.write_text(
        '// GENERATED by cinematic/scene_menu/build_ch3_thumb_data.py from the\n'
        '// chapter bake (R2 ch03/network/<lake>/manifest.json). Do not edit.\n'
        '// Season-end (30 Sep 2019) state of each example lake through the\n'
        '// revision checkpoint; vectors divided by their season-wide max |v|.\n'
        '\n'
        'export interface Ch3ThumbLake {\n'
        '  lake: string\n'
        '  true: string\n'
        '  pred: string\n'
        '  pw: number[]\n'
        '  gap: number[]\n'
        '  slstm: number[]\n'
        '  hidden: number[]\n'
        '  probs: number[]\n'
        '}\n'
        '\n'
        f'export const CLASSES = {json.dumps(index["classes"])}\n'
        f'export const COLORS: Record<string, string> = {json.dumps(index["colors"])}\n'
        '\n'
        'export const LAKES: Ch3ThumbLake[] = [\n'
        f'{body},\n'
        ']\n'
    )
    print('wrote', OUT, OUT.stat().st_size, 'bytes')


if __name__ == '__main__':
    main()
