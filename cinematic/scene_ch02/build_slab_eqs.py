"""
Chapter 2's THEORY segment (the idealized slab: Elmer/Ice vs the
shallow-stream theory) — its math, compiled by REAL LaTeX
with Ch.1's pipeline (cinematic/scene_ch01/build_theory_eqs.py: latex +
dvisvgm, Computer Modern, the TeX box as the viewBox, the baseline
recorded) — imported, not copied.

Two sets:
  * the slab's BOUNDARY-CONDITION cards (Ch2SlabBcCards.vue). Notation is
    the PNAS SI's (cinematic/source_data/manuscript_pnas/si/main.tex):
    the free surface σ·n = 0 on z = z_s (Eq. bc_surface), impenetrability
    u·n_b = 0 and the Weertman law τ_b = −C_b u_b with C_b = 0 inside the
    patch r ≤ R, c_b outside (Eqs. bc_bed_imp, bc_bed_weertman,
    bc_bed_patch) — LINEAR here (m = 1, Newtonian η = 10^14 Pa s, the SI
    Fig. S1 caption) — and the slab runs' coefficient c_b = 2ηγ/H (the
    sweep's γ; Chapter 1's C_b = γ·2η/h). The lateral walls are PERIODIC
    (SI §"Comparing theory with Stokes flow simulations": "with periodic
    boundary conditions"): the two x-walls are one, the two y-walls are one.
  * the FIELD NAMES of the sweep's manifest (fields_all), plain (the
    surface field) and over-lined (the depth average), for the colour bar
    and the deeper-dive viewer.

Outputs:
  cinematic/data/eq_slab/<name>.svg     (upload to R2 ch02/slab_eq_v1/)
  website/src/config/ch2SlabEqs.ts      (sizes in bp, committed)

Run:  python3 cinematic/scene_ch02/build_slab_eqs.py
Then: rclone copy cinematic/data/eq_slab r2:<bucket>/ch02/slab_eq_v1 --header-upload 'Cache-Control: public, max-age=31536000, immutable'
      (+ the same into website/.r2-cache/ch02/slab_eq_v1 for dev)
"""

import sys
import tempfile
from pathlib import Path

HERE = Path(__file__).resolve().parent
ROOT = HERE.parents[1]
sys.path.insert(0, str(ROOT / "cinematic" / "scene_ch01"))
import build_theory_eqs as bte  # noqa: E402

OUT = ROOT / "cinematic" / "data" / "eq_slab"
TS_OUT = ROOT / "website" / "src" / "config" / "ch2SlabEqs.ts"

SI = "PNAS SI"
EQS = {
    # ── the boundary conditions ──
    "loc_zs": (r"z = z_s", f"{SI} Eq. bc_surface"),
    "surface": (r"\boldsymbol{\sigma}\cdot\boldsymbol{n} = \boldsymbol{0}", f"{SI} Eq. bc_surface"),
    "loc_x": (r"x = \pm L/2", "the periodic x-walls"),
    "per_x": (r"\boldsymbol{u}\big|_{x=-L/2} = \boldsymbol{u}\big|_{x=+L/2}", "periodic in x (SI: periodic boundary conditions)"),
    "loc_y": (r"y = \pm L/2", "the periodic y-walls"),
    "per_y": (r"\boldsymbol{u}\big|_{y=-L/2} = \boldsymbol{u}\big|_{y=+L/2}", "periodic in y (SI: periodic boundary conditions)"),
    "loc_zb": (r"z = z_b", f"{SI} Eq. bc_bed_imp"),
    "bed_imp": (r"\boldsymbol{u}\cdot\boldsymbol{n}_b = 0", f"{SI} Eq. bc_bed_imp"),
    "bed_w": (r"\boldsymbol{\tau}_b = -C_b\,\boldsymbol{u}_b", f"{SI} Eq. bc_bed_weertman, m = 1"),
    "bed_cb": (r"C_b = \begin{cases} 0, & r \le R \\ c_b, & r > R \end{cases}", f"{SI} Eq. bc_bed_patch"),
    "bed_c": (r"c_b = \frac{2\eta\gamma}{H}", "the sweep's gamma (Ch.1: C_b = gamma 2 eta / h)"),
    "eta": (r"\eta = 10^{14}\ \mathrm{Pa\,s}", f"{SI} Fig. S1 caption (Newtonian)"),
}

FIELDS = {
    "st1": r"\sigma_{t1}",
    "st2": r"\sigma_{t2}",
    "trr": r"\tau_{rr}",
    "trt": r"\tau_{r\theta}",
    "ttt": r"\tau_{\theta\theta}",
    "txx": r"\tau_{xx}",
    "tyy": r"\tau_{yy}",
    "txy": r"\tau_{xy}",
    "srr": r"\Delta\sigma_{rr}",
    "stt": r"\Delta\sigma_{\theta\theta}",
    "srt": r"\Delta\sigma_{r\theta}",
}


def bar(tex: str) -> str:
    """Overline the symbol, not its subscript (the thesis figure's τ̄_rr)."""
    if tex.startswith(r"\Delta"):
        head, rest = r"\Delta\overline{\sigma}", tex[len(r"\Delta\sigma"):]
        return head + rest
    sym, sub = tex.split("_", 1)
    return rf"\overline{{{sym}}}_{sub}"


def main():
    OUT.mkdir(parents=True, exist_ok=True)
    items = dict(EQS)
    for k, t in FIELDS.items():
        items[f"f_{k}"] = (t, "field name (surface)")
        items[f"fb_{k}"] = (bar(t), "field name (depth average)")
    manifest = {}
    with tempfile.TemporaryDirectory() as td:
        wd = Path(td)
        for name, (tex, src) in items.items():
            svg, dims = bte.compile_one(bte.math(tex, True), None, "ink", wd, name)
            svg, W, H, base = bte.set_box(svg, dims["w"], dims["h"], dims["d"])
            (OUT / f"{name}.svg").write_text(svg)
            manifest[name] = dict(w=W, h=H, base=base, src=src)
            print(f"  {name:10s} {W:7.2f} x {H:6.2f} bp   [{src}]")
    lines = [
        "// GENERATED by cinematic/scene_ch02/build_slab_eqs.py — do not edit.",
        "// LaTeX (latex + dvisvgm, Computer Modern) for Chapter 2's slab",
        "// (the THEORY segment): the boundary-condition cards + the field names,",
        "// served from R2 ch02/slab_eq_v1/<name>.svg. Sizes in bp; base = image",
        "// top → baseline.",
        "export interface SlabEqBox { w: number; h: number; base: number }",
        "export const CH2_SLAB_EQ: Record<string, SlabEqBox> = {",
    ]
    for name, e in manifest.items():
        lines.append(f"  {name}: {{ w: {e['w']:.3f}, h: {e['h']:.3f}, base: {e['base']:.3f} }}, // {e['src']}")
    lines.append("}")
    TS_OUT.write_text("\n".join(lines) + "\n")
    print(f"wrote {len(manifest)} -> {TS_OUT.relative_to(ROOT)}")


if __name__ == "__main__":
    main()
